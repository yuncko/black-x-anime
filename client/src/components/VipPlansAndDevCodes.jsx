/**
 * Global Cloud-Synced VIP Enforcement Gate for the Website.
 * Reads the shared app config (/api/app/config, CDN-cached for 60 s) when the page
 * opens, every 5 minutes and whenever the tab becomes visible again, so a change
 * made by the developer from the website or the APK reaches every visitor within
 * minutes without a Firestore read per visitor every few seconds.
 */
export function GlobalVipEnforcementGate({ user, onVipUpdated, onOpenAuth }) {
  const [enforced, setEnforced] = useState(false);
  const [tierState, setTierState] = useState(() => resolveUserVipTier(user));

  useEffect(() => {
    setTierState(resolveUserVipTier(user));
  }, [user]);

  useEffect(() => {
    let mounted = true;
    // Shared app config from the server (cached on Vercel's CDN), not a Firestore
    // read per visitor every 5 seconds.
    const checkCloud = async () => {
      try {
        const res = await fetch('/api/app/config');
        if (!res.ok) return;
        const cfg = await res.json();
        if (mounted && typeof cfg?.enforced === 'boolean') setEnforced(cfg.enforced);
      } catch {}
    };
    checkCloud();
    const timer = setInterval(checkCloud, 5 * 60 * 1000);
    const onVisible = () => {
      if (document.visibilityState === 'visible') checkCloud();
    };
    document.addEventListener('visibilitychange', onVisible);
    return () => {
      mounted = false;
      clearInterval(timer);
      document.removeEventListener('visibilitychange', onVisible);
    };
  }, []);

  const isDev =
    user &&
    (user.role === 'developer' ||
      user.isDeveloper ||
      (user.email || '').toLowerCase() === 'mz0970mmz@gmail.com' ||
      (user.username || '').toLowerCase() === 'developer');

  const path = typeof window !== 'undefined' ? window.location.pathname : '';
  const isExemptRoute =
    path.startsWith('/login') ||
    path.startsWith('/register') ||
    path.startsWith('/admin') ||
    path.startsWith('/profile');

  if (!enforced || isDev || tierState !== 'free' || isExemptRoute) {
    return null;
  }

  return (
    <div
      style={{
        position: 'fixed',
        inset: 0,
        zIndex: 9000,
        background: 'rgba(0, 0, 0, 0.96)',
        backdropFilter: 'blur(20px)',
        overflowY: 'auto',
        padding: '2rem 1rem 4rem'
      }}
    >
      <div style={{ maxWidth: '960px', margin: '0 auto' }}>
        <div
          style={{
            display: 'flex',
            justifyContent: 'space-between',
            alignItems: 'center',
            flexWrap: 'wrap',
            gap: '0.75rem',
            marginBottom: '1.25rem',
            padding: '1rem 1.25rem',
            borderRadius: '16px',
            background: '#0a0a0f',
            border: '1px solid rgba(255,255,255,0.2)'
          }}
        >
          <div>
            <div style={{ fontWeight: 900, fontSize: '1.05rem', color: '#fff' }}>
              🔒 نظام عضوية Hearbor VIP مفعل حالياً على جميع النسخ
            </div>
            <div style={{ fontSize: '0.82rem', color: 'rgba(255,255,255,0.68)' }}>
              اشترك في إحدى باقات VIP أو أدخل كود التفعيل الفوري، أو سجّل دخولك إذا كنت مشتركاً أو مطور المنصة.
            </div>
          </div>
          <button
            type="button"
            onClick={() => onOpenAuth ? onOpenAuth('login') : (window.location.href = '/profile')}
            style={{
              padding: '0.6rem 1.15rem',
              borderRadius: '11px',
              background: '#ffffff',
              color: '#000000',
              border: 'none',
              fontWeight: 900,
              fontSize: '0.84rem',
              cursor: 'pointer'
            }}
          >
            🔐 تسجيل الدخول لحسابك / المطور
          </button>
        </div>

        <VipPlansSection
          user={user}
          onVipUpdated={(u) => {
            setTierState(resolveUserVipTier(u));
            onVipUpdated?.(u);
          }}
        />
      </div>
    </div>
  );
}

