// Icons that read better solid (rating stars).
const FILLED_BY_DEFAULT = new Set(['star']);

// Pictographic emoji plus the symbol glyphs older builds used as pseudo-icons (black star,
// check mark, multiplication x, trigram menu, ...). Plain typography (arrows, bullets,
// dashes, copyright / trademark signs) is left alone.
const EMOJI_RE =
  /(?:(?![\u00A9\u00AE\u2122])\p{Extended_Pictographic})|[\u{1F000}-\u{1FAFF}\u2605\u2606\u2713\u2715\u2630-\u2637\u21C5\u21BB\u276F\u26F6\u232B\u24D8\u25B2\u25BC]|\uFE0F|\u200D|\u20E3/gu;

/** Remove emoji from runtime text (toasts, legacy values saved on the device by older builds). */
export function stripEmoji(text) {
  return String(text ?? '')
    .replace(EMOJI_RE, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\(\s+/g, '(')
    .replace(/\s+\)/g, ')')
    .trim();
}

export function hasBxIcon(name) {
  return Boolean(name && ICONS[name]);
}

export default function BxIcon({ name, size = '1.15em', strokeWidth = 2.1, filled, spin = false, className = '', style, label, ...rest }) {
  const Icon = ICONS[name];
  if (!Icon) return null;
  const solid = filled ?? FILLED_BY_DEFAULT.has(name);
  return (
    <Icon
      size={size}
      strokeWidth={strokeWidth}
      fill={solid ? 'currentColor' : 'none'}
      focusable="false"
      aria-hidden={label ? undefined : true}
      aria-label={label || undefined}
      role={label ? 'img' : undefined}
      className={`bx-ico${spin || name === 'loader' ? ' bx-ico-spin' : ''}${className ? ` ${className}` : ''}`}
      style={style}
      {...rest}
    />
  );
}
